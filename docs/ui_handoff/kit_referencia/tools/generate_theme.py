#!/usr/bin/env python3
"""Single source of truth for RGB565 embedded palettes and matching CSS preview."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
tokens = json.loads((ROOT / "config/ui_tokens.json").read_text(encoding="utf-8"))
themes = tokens["themes"]
fields = ("primary", "secondary", "muted", "surface", "background")

def to565(s: str) -> int:
    if not re.fullmatch(r"#[0-9A-Fa-f]{6}", s):
        raise ValueError(f"Cor hexadecimal invalida: {s}")
    x = int(s[1:], 16)
    r, g, b = (x >> 16) & 255, (x >> 8) & 255, x & 255
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

head = [
    "// Generated by tools/generate_theme.py. Do not edit manually.",
    "#pragma once", "#include <stdint.h>",
    "namespace radio_ui {",
    "struct Palette { uint16_t primary, secondary, muted, surface, background; };",
    "enum class ThemeId : uint8_t { " + ", ".join(k.upper() for k in themes) + " };",
    "constexpr Palette PALETTES[] = {"
]
for name, theme in themes.items():
    head.append("    {" + ", ".join(f"0x{to565(theme[f]):04X}" for f in fields) + "}, // " + name)
head += ["};", "constexpr unsigned THEME_COUNT = sizeof(PALETTES) / sizeof(PALETTES[0]);", "}"]
(ROOT / "src/ui_theme_generated.hpp").write_text("\n".join(head) + "\n", encoding="utf-8")

css = ["/* Generated by tools/generate_theme.py. Do not edit manually. */"]
for name, theme in themes.items():
    css.append(".theme-" + name + " { " + " ".join(f"--ui-{f}: {theme[f]};" for f in fields) + " }")
(ROOT / "web/ui_themes.css").write_text("\n".join(css) + "\n", encoding="utf-8")
print(f"Geradas {len(themes)} paletas C++ (RGB565) e CSS.")
